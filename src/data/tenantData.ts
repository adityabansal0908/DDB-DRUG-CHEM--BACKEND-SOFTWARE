// Helper to convert Organization to CompanyProfile
export function orgToCompanyProfile(org: Organization): CompanyProfile {
  return {
    id: org.id,
    name: org.name,
    legalName: org.legalName,
    tagline: org.tagline || '',
    logoUrl: org.logoUrl,
    logoType: org.logoType,
    presetIconId: org.presetIconId,
    primaryColor: org.primaryColor,
    drugLicenseNo: org.drugLicenseNo || '',
    gstin: org.gstin || '',
    panNo: org.panNo,
    cin: org.cin,
    fssaiLicenseNo: org.fssaiLicenseNo,
    headOfficeAddress: org.headOfficeAddress || '',
    city: org.city || '',
    state: org.state || '',
    pincode: org.pincode || '',
    contactEmail: org.contactEmail,
    contactPhone: org.contactPhone || '',
    website: org.website,
    invoicePrefix: org.invoicePrefix || 'INV',
    currencySymbol: org.currencySymbol || '₹',
    status: org.status,
    maxRepsAllowed: org.maxReps,
    planName: `${org.plan.charAt(0).toUpperCase() + org.plan.slice(1)} Plan`,
    updatedAt: org.updatedAt
  };
}

